    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
    try {
        FileWriter fw = new FileWriter("TrangChu.txt");
        PrintWriter pw = new PrintWriter(fw);

        pw.println("#ACCOUNT");
        pw.println("TK=" + currentUser);
        pw.println("MK=" + currentPass);
        pw.println("");

        pw.println("#DAY:0");

        for (int i = 0; i < soLuongHD; i++) {
            pw.println("Hoạt động " + (i+1) + ": " + txtHoatDong[i].getText());
        }


        pw.print("TICK: ");
        for (int i = 0; i < soLuongHD; i++) {
            pw.print(rdHoanThanh[i].isSelected() ? "1" : "0");
            if (i < soLuongHD - 1) pw.print(" ");
        }
        pw.println();


        pw.println("NOTE: " + jTextArea2.getText());
        pw.println("#END");

        pw.close();

        JOptionPane.showMessageDialog(this, "Đã lưu thành công vào TrangChu.txt!");

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Lỗi: " + e.getMessage());
    }
    }//GEN-LAST:event_jButton3ActionPerformed

