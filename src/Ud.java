private void loadTrangChuData() {
    try {
        File file = new File("TrangChu.txt");
        if (!file.exists()) return;

        List<String> lines = Files.readAllLines(file.toPath());

        
        for (int i = 0; i < 5; i++) {
            txtHoatDong[i].setVisible(false);
            txtHoatDong[i].setText("");
            rdHoanThanh[i].setVisible(false);
            rdHoanThanh[i].setSelected(false);
        }

        jTextArea2.setText("");
        int indexHD = 0;

        for (String line : lines) {

            if (line.startsWith("#")) continue;

            
            if (line.startsWith("Hoạt động")) {
                String value = line.substring(line.indexOf(":") + 1).trim();

                if (indexHD < 5) {
                    txtHoatDong[indexHD].setText(value);
                    txtHoatDong[indexHD].setVisible(true);
                    rdHoanThanh[indexHD].setVisible(true);
                }
                indexHD++;
            }

            
            if (line.startsWith("TICK:")) {
                String[] tick = line.replace("TICK:", "").trim().split(" ");
                for (int i = 0; i < tick.length && i < 5; i++) {
                    rdHoanThanh[i].setSelected(tick[i].equals("1"));
                }
            }

            
            if (line.startsWith("NOTE:")) {
                jTextArea2.setText(line.substring(5).trim());
            }
        }

        soLuongHD = indexHD;

    } catch (Exception e) {
        System.out.println("Lỗi load: " + e.getMessage());
    }
}



private void kiemTraNgayReset() {
    try {
        File f = new File("ThongTin.txt");
        String homNay = java.time.LocalDate.now().toString();

        if (!f.exists()) {
            FileWriter fw = new FileWriter(f);
            fw.write("NgayLuu=" + homNay);
            fw.close();
            return;
        }

        BufferedReader br = new BufferedReader(new FileReader(f));
        String dong = br.readLine();
        br.close();

        if (dong == null) return;

        String ngayLuu = dong.split("=")[1];

        if (!ngayLuu.equals(homNay)) {

            for (JTextField txt : txtHoatDong) txt.setText("");
            for (JRadioButton rd : rdHoanThanh) rd.setSelected(false);
            jTextArea2.setText("");

            FileWriter fw = new FileWriter("ThongTin.txt");
            fw.write("NgayLuu=" + homNay);
            fw.close();
        }

    } catch (Exception e) {
        System.out.println("Lỗi: " + e.getMessage());
    }
}







    
